"""Write docs/MODEL_REPORT.md from the saved evaluation bundle and cross-check it
against the MLflow tracking store.

Usage (from the project root, after train_models):
    python -m scripts.evaluate_models
"""
from __future__ import annotations

import os
import sys

import pandas as pd

from src.models.inference import ModelArtifactsMissing, load_bundle
from src.utils import config as C
from src.utils.logging import get_logger

os.environ.setdefault("MLFLOW_DISABLE_AGENT_HINT", "1")
log = get_logger("evaluate_models")

PRETTY = {"logistic_regression": "Logistic Regression", "random_forest": "Random Forest", "xgboost": "XGBoost",
          "mean_baseline": "Mean baseline", "ridge": "Ridge", "cohort_median_benchmark": "Comparable-median rule"}


def _md_table(df: pd.DataFrame) -> str:
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for _, r in df.iterrows():
        lines.append("| " + " | ".join(str(r[c]) for c in cols) + " |")
    return "\n".join(lines)


def mlflow_crosscheck(evaluation: dict) -> list[str]:
    """Confirm every run ID in the bundle exists in MLflow with the same test metric."""
    try:
        import mlflow
        from mlflow.tracking import MlflowClient
    except ImportError:
        return ["MLflow not installed; cross-check skipped."]
    db = C.PROJECT_ROOT / "mlflow.db"
    if C.MLFLOW_TRACKING_URI.startswith("sqlite") and not db.exists():
        return ["mlflow.db not found; cross-check skipped (expected on a deployed app)."]
    mlflow.set_tracking_uri(C.MLFLOW_TRACKING_URI)
    client = MlflowClient()
    notes = []
    checks = [(k, v, "test_roc_auc", v["test"]["roc_auc"]) for k, v in evaluation["classification"]["results"].items()]
    checks += [(k, v, "test_r2", v["test"]["r2"]) for k, v in evaluation["regression"]["results"].items()]
    ok = 0
    for key, res, metric, expected in checks:
        run = client.get_run(res["run_id"])
        logged = run.data.metrics.get(metric)
        if logged is None or abs(logged - expected) > 1e-9:
            notes.append(f"MISMATCH {key}: bundle {expected} vs MLflow {logged}")
        else:
            ok += 1
    try:
        mv = client.get_model_version_by_alias(C.REGISTERED_CLASSIFIER, "champion")
        notes.append(f"Registry: {C.REGISTERED_CLASSIFIER} v{mv.version} (alias champion), status {mv.status}.")
    except Exception as exc:  # registry optional
        notes.append(f"Registry lookup failed: {exc}")
    notes.insert(0, f"{ok}/{len(checks)} runs found in MLflow with matching test metrics.")
    return notes


def build_report() -> str:
    b = load_bundle()
    meta, ev = b.metadata, b.evaluation
    clf, reg = ev["classification"], ev["regression"]
    champ = meta["classifier"]["champion"]

    crows = []
    for k, r in clf["results"].items():
        crows.append({"Track": r["track"], "Model": PRETTY[r["model"]] + (" ★" if k == champ else ""),
                      "Val AUC": f"{r['val']['roc_auc']:.4f}", "Test AUC": f"{r['test']['roc_auc']:.4f}",
                      "Precision": f"{r['test']['precision']:.4f}", "Recall": f"{r['test']['recall']:.4f}",
                      "F1": f"{r['test']['f1']:.4f}", "Accuracy": f"{r['test']['accuracy']:.4f}",
                      "Brier": f"{r['test']['brier']:.4f}", "ECE": f"{r['test']['ece']:.4f}"})
    rrows = [{"Model": PRETTY[k], "Val R²": f"{r['val']['r2']:+.4f}", "Test R²": f"{r['test']['r2']:+.4f}",
              "Test MAE (₹ L)": f"{r['test']['mae']:.2f}", "Test RMSE (₹ L)": f"{r['test']['rmse']:.2f}"}
             for k, r in reg["results"].items()]
    cm = clf["results"][champ]["curves"]["confusion_matrix"]
    imp = pd.DataFrame(clf["importance"][champ]).head(6)
    imp_attr = pd.DataFrame(clf["importance"][clf["selection"]["best_attributes_only"]]).head(4)
    checks = mlflow_crosscheck(ev)

    return f"""# Model Evaluation Report — PropWise AI

Generated by `python -m scripts.evaluate_models` from `models/evaluation.json` (model bundle created
{meta['created_at']}). Every number below was computed by `scripts/train_models.py`; none are typed by hand.

## 1. Setup
- **Data:** {meta['dataset']['rows']:,} listings, SHA-256 `{meta['dataset']['sha256'][:16]}…`
- **Split:** random, stratified by city: train {meta['dataset']['splits']['train']:,} / validation
  {meta['dataset']['splits']['val']:,} / test {meta['dataset']['splits']['test']:,} (seed {C.RANDOM_STATE}).
  Rows are independent listings with no repeats and no time index, so group- or time-aware validation is not required.
- **Label:** {meta['label']['definition']}
- **Class balance:** {meta['label']['positive_rates']['train']:.1%} positive (train), {meta['label']['positive_rates']['test']:.1%} (test).
- **Selection:** {clf['selection']['criterion']}. Test metrics were not used for selection.

## 2. Investment classification

{_md_table(pd.DataFrame(crows))}

★ = champion. **Interpretation.** The *listing* track includes price and area. The label is a deterministic function
of price ÷ area against a cohort median, so these models learn to reproduce the rule; near-perfect scores
are expected and are **not** evidence that the model predicts investment returns. The *attributes-only* track removes
price. Its ≈0.78 AUC comes almost entirely from area (₹/sqft = price ÷ area, and price is independent of area in this data).

**Champion confusion matrix (test, threshold 0.5)**

| | Pred: above | Pred: good value |
|---|---|---|
| **Actual: above** | {cm[0][0]:,} | {cm[0][1]:,} |
| **Actual: good value** | {cm[1][0]:,} | {cm[1][1]:,} |

**Calibration.** Test ECE {meta['classifier']['test_ece']:.4f} (threshold {C.MAX_DISPLAY_ECE}) →
probabilities {'are' if meta['classifier']['show_probability'] else 'are not'} displayed in the app.

**Permutation importance (drop in test ROC-AUC when shuffled)**

Champion, listing track: {', '.join(f"{r.feature} {r.importance:.3f}" for r in imp.itertuples())}

Attributes-only: {', '.join(f"{r.feature} {r.importance:.3f}" for r in imp_attr.itertuples())}

## 3. Valuation signal test (regression on current price)

{_md_table(pd.DataFrame(rrows))}

**Interpretation.** No learned model beats predicting the mean (R² ≈ 0), and the comparable-median rule
(cohort median ₹/sqft × area) is worse than the mean because price is unrelated to area in this data.
**There is no valuation signal to learn**, so the app does not present an "estimated current value".
Five-year values are produced by the transparent scenario engine (`src/models/scenario.py`), not by a model.
Mean absolute error is flat across cities (see `models/evaluation.json → regression.diagnostics.mae_by_city`).

## 4. Five-year scenarios
Future value = current price × (1 + r)^{C.HORIZON_YEARS}, with defaults
{', '.join(f'{k} {v:.0%}' for k, v in C.SCENARIO_RATES.items())}.
{C.RATE_RATIONALE}
Sources: {'; '.join(f"[{s['name']}]({s['url']})" for s in C.RATE_SOURCES)}.

## 5. MLflow cross-check
{chr(10).join('- ' + n for n in checks)}

## 6. Versions
{', '.join(f'{k} {v}' for k, v in meta['versions'].items())}
"""


def main() -> int:
    try:
        report = build_report()
    except ModelArtifactsMissing as exc:
        log.error(str(exc))
        return 1
    out = C.DOCS_DIR / "MODEL_REPORT.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(report, encoding="utf-8")
    log.info("Wrote %s", out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
